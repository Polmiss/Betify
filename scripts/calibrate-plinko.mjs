import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { simulatePlinko, PLINKO_ROWS_OPTIONS } from '../src/games/instant/plinko-physics.js';

// The complete, equally likely release space is counted, not sampled for an estimate.
const poolSize = 16384;
const counts = {};
for (const rows of PLINKO_ROWS_OPTIONS) {
  counts[rows] = Array(rows + 1).fill(0);
  for (let seed = 0; seed < poolSize; seed++) {
    const { slot } = simulatePlinko(seed, rows);
    counts[rows][slot]++;
    counts[rows][rows - slot]++;
  }
  if (counts[rows].some((count) => count === 0)) throw new Error('Unreachable bucket');
  console.log(`${rows} rows: ${counts[rows].join(', ')}`);
}
const physics = (await readFile(new URL('../src/games/instant/plinko-physics.js', import.meta.url), 'utf8')).replace(/\r\n/g, '\n');
const data = { poolSize, physicsSha256: createHash('sha256').update(physics).digest('hex'), counts };
const source = '// Generated by node scripts/calibrate-plinko.mjs; every release is enumerated.\nexport const PLINKO_DISTRIBUTION = ' + JSON.stringify(data, null, 2) + ';\n';
await writeFile(new URL('../src/games/instant/plinko-distribution.js', import.meta.url), source);
